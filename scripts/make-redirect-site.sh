#!/usr/bin/env bash
# Generates the static site for a small redirect repository that keeps an app's old GitHub Pages
# URLs working after this repository is renamed (docs/RENAME.md). For Tendr:
#   scripts/make-redirect-site.sh tendr https://0x63616c.github.io/apps/tendr ../tendr-redirect
# serves https://0x63616c.github.io/tendr/, /tendr/privacy/ and /tendr/support/ as redirects to
# the same pages under /apps/tendr/. Any other old path redirects through 404.html.
set -euo pipefail
app=${1:?usage: make-redirect-site.sh <app> <new-base-url> <output-dir>}
base=${2:?usage: make-redirect-site.sh <app> <new-base-url> <output-dir>}
out=${3:?usage: make-redirect-site.sh <app> <new-base-url> <output-dir>}
base=${base%/}

page() { # page <file> <target-url>
  mkdir -p "$(dirname "$1")"
  cat > "$1" <<HTML
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Moved</title>
<meta name="robots" content="noindex">
<link rel="canonical" href="$2">
<meta http-equiv="refresh" content="0; url=$2">
<script>location.replace("$2" + location.search + location.hash);</script>
</head>
<body style="font-family: -apple-system, system-ui, sans-serif; padding: 2rem;">
<p>This page has moved to <a href="$2">$2</a>.</p>
</body>
</html>
HTML
}

mkdir -p "$out"
page "$out/index.html" "$base/"
page "$out/privacy/index.html" "$base/privacy/"
page "$out/support/index.html" "$base/support/"
# GitHub Pages serves 404.html for anything else: keep the rest of the path.
cat > "$out/404.html" <<HTML
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Moved</title>
<meta name="robots" content="noindex">
<script>
  var rest = location.pathname.replace(/^\/$app\/?/, "");
  location.replace("$base/" + rest + location.search + location.hash);
</script>
</head>
<body style="font-family: -apple-system, system-ui, sans-serif; padding: 2rem;">
<p>This page has moved to <a href="$base/">$base/</a>.</p>
</body>
</html>
HTML
touch "$out/.nojekyll"
cat > "$out/README.md" <<MD
# $app (moved)

GitHub Pages redirects for $app's original URLs. The app's site now lives at $base/.
Generated by scripts/make-redirect-site.sh in the apps monorepo.
MD
echo "Wrote redirect site for /$app/ → $base/ in $out"
